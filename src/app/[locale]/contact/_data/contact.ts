export function getContactOptions(locale: Locale) {
  const number = new Intl.NumberFormat(intlLocale(locale));
  const labels = copy[locale];
  const collection = <K extends keyof typeof en>(key: K) =>
    values[key].map((value) => ({
      value,
      label: (labels[key] as Record<string, string>)[value].replace(
        /\{(2|5|10)\}/g,
        (_, amount: string) => number.format(Number(amount)),
      ),
    }));
  return {
    desktopNeeds: collection("desktopNeeds"),
    mobileNeeds: collection("mobileNeeds"),
    desktopDocuments: collection("desktopDocuments"),
    mobileDocuments: collection("mobileDocuments"),
    budgets: collection("budgets"),
  };
}
